package org.kylepitcock.mccompat.loader.meta;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import java.nio.charset.StandardCharsets;
import java.util.HashSet;
import java.util.Set;
import org.kylepitcock.mccompat.loader.LegacyJar;
import org.kylepitcock.mccompat.loader.LegacyModDecl;
import org.objectweb.asm.AnnotationVisitor;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/**
 * Produces what NeoForge needs to load a translated jar as an ordinary mod: a {@code neoforge.mods.toml}
 * and, per legacy mod, a tiny {@code @Mod}-annotated entrypoint class that hands control to the shim.
 */
public final class ModMetadataGenerator {
    public static final String RUNTIME_MOD_ID = "retrofit";
    public static final String BOOTSTRAP = "org/kylepitcock/mccompat/core/LegacyBootstrap";
    public static final String LEGACY_JSON = "META-INF/mccompat/legacy-mods.json";
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private ModMetadataGenerator() {}

    /**
     * Modern ids of every legacy mod being loaded, or null if unknown. A legacy "required-after:X" only becomes a
     * mandatory dependency when X is one of them: in 1.7.10 many dependencies were satisfied by coremod dummy
     * containers or {@code @API} packages (CodeChickenCore, CoFHLib, OpenPeripheralApi) that are not mods here.
     */
    private static volatile Set<String> loadedMods;

    public static void setLoadedMods(java.util.Collection<String> modernIds) {
        loadedMods = Set.copyOf(modernIds);
    }

    public static String entrypointName(LegacyModDecl decl) {
        return "mccompat/generated/" + decl.modernId() + "/LegacyModEntrypoint";
    }

    public static byte[] modsToml(LegacyJar jar) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by MC Compatibility from legacy jar ").append(jar.fileName()).append('\n');
        sb.append("modLoader=\"javafml\"\n");
        sb.append("loaderVersion=\"[1,)\"\n");
        sb.append("license=").append(q("Unknown (legacy " + jar.version.id() + " mod)")).append('\n');
        sb.append("showAsResourcePack=false\n\n");
        Set<String> ids = new HashSet<>();
        for (LegacyModDecl mod : jar.mods) ids.add(mod.modernId());
        for (LegacyModDecl mod : jar.mods) {
            sb.append("[[mods]]\n");
            sb.append("modId=").append(q(mod.modernId())).append('\n');
            sb.append("version=").append(q(sanitizeVersion(mod.version))).append('\n');
            sb.append("displayName=").append(q(mod.name + " [" + jar.version.id() + "]")).append('\n');
            if (!mod.authors.isEmpty()) sb.append("authors=").append(q(String.join(", ", mod.authors))).append('\n');
            if (mod.credits != null) sb.append("credits=").append(q(mod.credits)).append('\n');
            if (mod.url != null) sb.append("displayURL=").append(q(mod.url)).append('\n');
            if (mod.logoFile != null) sb.append("logoFile=").append(q(mod.logoFile.startsWith("/") ? mod.logoFile.substring(1) : mod.logoFile)).append('\n');
            sb.append("description=").append(q((mod.description == null ? "" : mod.description)
                    + "\n\nLegacy Forge " + jar.version.id() + " mod running through MC Compatibility (legacy id: " + mod.legacyId + ")")).append("\n\n");

            dependency(sb, mod.modernId(), RUNTIME_MOD_ID, true, "AFTER");
            for (LegacyModDecl.Dependency dep : mod.parsedDependencies()) {
                if (dep.isPlatform()) continue;
                String target = LegacyModDecl.toModernId(dep.legacyId());
                if (target.equals(mod.modernId())) continue;
                // Dependencies between mods of the same jar are implicit; FML rejects self-file cycles badly.
                if (ids.contains(target) && !dep.required()) continue;
                boolean required = dep.required() && (loadedMods == null || loadedMods.contains(target));
                dependency(sb, mod.modernId(), target, required, dep.ordering());
            }
        }
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    private static void dependency(StringBuilder sb, String owner, String target, boolean required, String ordering) {
        sb.append("[[dependencies.").append(owner).append("]]\n");
        sb.append("modId=").append(q(target)).append('\n');
        sb.append("type=").append(q(required ? "required" : "optional")).append('\n');
        // Legacy version ranges compare against legacy version strings that rarely follow Maven ordering.
        sb.append("versionRange=\"*\"\n");
        sb.append("ordering=").append(q(ordering)).append('\n');
        sb.append("side=\"BOTH\"\n\n");
    }

    /** Runtime-facing description of the legacy mods inside a translated jar. */
    public static byte[] legacyJson(LegacyJar jar) {
        JsonObject root = new JsonObject();
        root.addProperty("version", jar.version.id());
        root.addProperty("sourceJar", jar.fileName());
        JsonArray mods = new JsonArray();
        for (LegacyModDecl mod : jar.mods) {
            JsonObject o = new JsonObject();
            o.addProperty("legacyId", mod.legacyId);
            o.addProperty("modernId", mod.modernId());
            o.addProperty("mainClass", mod.mainClass.replace('/', '.'));
            o.addProperty("name", mod.name);
            o.addProperty("version", mod.version);
            o.addProperty("dependencies", mod.dependencies);
            o.addProperty("clientSideOnly", mod.clientSideOnly);
            o.addProperty("serverSideOnly", mod.serverSideOnly);
            mods.add(o);
        }
        root.add("mods", mods);
        return GSON.toJson(root).getBytes(StandardCharsets.UTF_8);
    }

    /**
     * {@code @Mod("<modernId>") public final class LegacyModEntrypoint} whose constructor calls
     * {@code LegacyBootstrap.construct(version, legacyId, mainClass, modBus, container)}.
     */
    public static byte[] entrypointClass(LegacyJar jar, LegacyModDecl mod) {
        String name = entrypointName(mod);
        ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_MAXS);
        cw.visit(Opcodes.V17, Opcodes.ACC_PUBLIC | Opcodes.ACC_FINAL | Opcodes.ACC_SUPER, name, null, "java/lang/Object", null);
        AnnotationVisitor av = cw.visitAnnotation("Lnet/neoforged/fml/common/Mod;", true);
        av.visit("value", mod.modernId());
        av.visitEnd();

        MethodVisitor mv = cw.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "(Lnet/neoforged/bus/api/IEventBus;Lnet/neoforged/fml/ModContainer;)V", null, null);
        mv.visitCode();
        mv.visitVarInsn(Opcodes.ALOAD, 0);
        mv.visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false);
        mv.visitLdcInsn(jar.version.id());
        mv.visitLdcInsn(mod.legacyId);
        mv.visitLdcInsn(mod.mainClass.replace('/', '.'));
        mv.visitVarInsn(Opcodes.ALOAD, 1);
        mv.visitVarInsn(Opcodes.ALOAD, 2);
        mv.visitMethodInsn(Opcodes.INVOKESTATIC, BOOTSTRAP, "construct",
                "(Ljava/lang/String;Ljava/lang/String;Ljava/lang/String;Lnet/neoforged/bus/api/IEventBus;Lnet/neoforged/fml/ModContainer;)V", false);
        mv.visitInsn(Opcodes.RETURN);
        mv.visitMaxs(0, 0);
        mv.visitEnd();
        cw.visitEnd();
        return cw.toByteArray();
    }

    /** FML parses versions as Maven artifact versions; strip characters that make it choke. */
    static String sanitizeVersion(String v) {
        if (v == null || v.isBlank()) return "0.0.0-legacy";
        String s = v.trim().replaceAll("[^A-Za-z0-9.+_-]", "_");
        return Character.isDigit(s.charAt(0)) ? s : "0-" + s;
    }

    /** TOML basic string with escapes. */
    static String q(String s) {
        StringBuilder sb = new StringBuilder("\"");
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> { }
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }
}
