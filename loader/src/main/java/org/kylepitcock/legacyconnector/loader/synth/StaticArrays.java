package org.kylepitcock.legacyconnector.loader.synth;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import org.kylepitcock.legacyconnector.loader.LegacyVersion;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/**
 * Vanilla static fields that hold literal arrays (ItemDye's names and colours, flower names, sheep colours): the
 * synthesized classes that stand in for such vanilla classes initialise them with the real values
 * (table generated by tools/extract_static_arrays.sh).
 */
public final class StaticArrays {
    private record Entry(String desc, String value) {}

    private static final Map<LegacyVersion, Map<String, Entry>> BY_KEY = new HashMap<>();
    private static final Map<LegacyVersion, Map<String, String>> SRG = new HashMap<>();

    private StaticArrays() {}

    private static synchronized void load(LegacyVersion version) {
        if (BY_KEY.containsKey(version)) return;
        Map<String, Entry> values = new HashMap<>();
        Map<String, String> srg = new HashMap<>();
        String base = "legacyconnector/legacy/" + version.id() + "/";
        try (InputStream in = StaticArrays.class.getClassLoader().getResourceAsStream(base + "static-arrays.txt")) {
            if (in != null) {
                BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
                for (String line; (line = r.readLine()) != null; ) {
                    String[] p = line.split(" ", 4);
                    if (p.length == 4) values.put(p[0].replace('/', '.') + "." + p[1], new Entry(p[2], p[3]));
                }
            }
        } catch (Exception e) {
            // no table
        }
        try (InputStream in = StaticArrays.class.getClassLoader().getResourceAsStream(base + "fields.txt")) {
            if (in != null) {
                BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
                for (String line; (line = r.readLine()) != null; ) {
                    String[] p = line.split(" ");
                    if (p.length == 5) srg.put(p[1].replace('/', '.') + "." + p[2], p[0]);
                }
            }
        } catch (Exception e) {
            // no table
        }
        SRG.put(version, srg);
        BY_KEY.put(version, values);
    }

    /** (srg field name, descriptor) of the literal arrays vanilla's {@code legacyOwner} (dotted name) declares. */
    public static List<String[]> entriesFor(LegacyVersion version, String legacyOwner) {
        load(version);
        List<String[]> out = new ArrayList<>();
        String prefix = legacyOwner + ".";
        for (var e : BY_KEY.get(version).entrySet()) {
            if (e.getKey().startsWith(prefix) && e.getKey().indexOf('.', prefix.length()) < 0) {
                out.add(new String[] {e.getKey().substring(prefix.length()), e.getValue().desc()});
            }
        }
        return out;
    }

    /** Emits code that leaves the array for {@code owner.field} on the stack; false when there is no known value. */
    public static boolean push(MethodVisitor mv, LegacyVersion version, String legacyOwner, String field, String desc) {
        load(version);
        String key = legacyOwner + "." + field;
        Entry e = BY_KEY.get(version).get(key);
        if (e == null) {
            String srg = SRG.get(version).get(key);
            if (srg != null) e = BY_KEY.get(version).get(legacyOwner + "." + srg);
        }
        if (e == null || !e.desc().equals(desc)) return false;
        switch (desc) {
            case "[Ljava/lang/String;" -> {
                List<String> items = split(e.value(), '|');
                mv.visitLdcInsn(items.size());
                mv.visitTypeInsn(Opcodes.ANEWARRAY, "java/lang/String");
                for (int i = 0; i < items.size(); i++) {
                    mv.visitInsn(Opcodes.DUP);
                    mv.visitLdcInsn(i);
                    mv.visitLdcInsn(unescape(items.get(i)));
                    mv.visitInsn(Opcodes.AASTORE);
                }
            }
            case "[I" -> {
                List<String> items = split(e.value(), '|');
                mv.visitLdcInsn(items.size());
                mv.visitIntInsn(Opcodes.NEWARRAY, Opcodes.T_INT);
                for (int i = 0; i < items.size(); i++) {
                    mv.visitInsn(Opcodes.DUP);
                    mv.visitLdcInsn(i);
                    mv.visitLdcInsn(Integer.parseInt(items.get(i)));
                    mv.visitInsn(Opcodes.IASTORE);
                }
            }
            case "[F" -> floats(mv, split(e.value(), '|'));
            case "[[F" -> {
                List<String> rows = split(e.value(), ';');
                mv.visitLdcInsn(rows.size());
                mv.visitTypeInsn(Opcodes.ANEWARRAY, "[F");
                for (int i = 0; i < rows.size(); i++) {
                    mv.visitInsn(Opcodes.DUP);
                    mv.visitLdcInsn(i);
                    floats(mv, split(rows.get(i), '|'));
                    mv.visitInsn(Opcodes.AASTORE);
                }
            }
            default -> {
                return false;
            }
        }
        return true;
    }

    private static void floats(MethodVisitor mv, List<String> items) {
        mv.visitLdcInsn(items.size());
        mv.visitIntInsn(Opcodes.NEWARRAY, Opcodes.T_FLOAT);
        for (int i = 0; i < items.size(); i++) {
            mv.visitInsn(Opcodes.DUP);
            mv.visitLdcInsn(i);
            mv.visitLdcInsn(Float.parseFloat(items.get(i)));
            mv.visitInsn(Opcodes.FASTORE);
        }
    }

    /** Splits on an unescaped separator (backslash escapes the next character). */
    private static List<String> split(String s, char sep) {
        List<String> out = new ArrayList<>();
        StringBuilder cur = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\\' && i + 1 < s.length()) {
                cur.append(c).append(s.charAt(++i));
            } else if (c == sep) {
                out.add(cur.toString());
                cur.setLength(0);
            } else {
                cur.append(c);
            }
        }
        out.add(cur.toString());
        return out;
    }

    private static String unescape(String s) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\\' && i + 1 < s.length()) {
                char n = s.charAt(++i);
                sb.append(n == 'p' ? '|' : n == 's' ? ';' : n);
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }
}
