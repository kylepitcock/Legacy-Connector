package org.kylepitcock.legacyconnector.loader.transform;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashSet;
import java.util.Set;
import java.util.TreeSet;
import java.util.zip.GZIPInputStream;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.InsnList;
import org.objectweb.asm.tree.InsnNode;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;
import org.objectweb.asm.tree.VarInsnNode;

/**
 * Class SHAPE changes between Minecraft 1.20.1 and 1.21.1: a game type that mod classes extend or implement and that is not what it was (these fail when the
 * class loads, before any feature runs: {@code IncompatibleClassChangeError}, "cannot inherit from final").
 * <ul>
 *   <li><b>final classes and records that 1.20.1 left open</b> (Forge opened many with its own transformers; {@code ModelPart}, {@code MapDecoration},
 *   {@code Ingredient.TagValue}, {@code BlockElementFace}, {@code CompoundIngredient}...): a mod class that extends one gets a {@code public-f} line in the
 *   jar's access transformer. The set is {@code mc-closed.txt.gz} (generated by {@code tools/dev/gen_mc_closed.py} from the 1.21.1 + NeoForge jar).</li>
 *   <li><b>interface that became a record</b>: {@code BlockSource} (Position + four getters in 1.20.1; {@code record BlockSource(level, pos, state, blockEntity)}
 *   in 1.21.1). A mod class that {@code implements} it (and extends nothing else) now extends the record (opened as above, canonical constructor called with
 *   nulls, since the mod answers through its own getters), implements {@code LegacyBlockSource} (the 1.20.1 interface, which the call helpers of
 *   {@code MiscCompat} prefer over the record's slots) and bridges the record's accessors to its own getters. A class that also has another superclass cannot
 *   be converted: it is reported.</li>
 * </ul>
 */
final class ClassShape1201 {
    static final String BLOCK_SOURCE = "net/minecraft/core/dispenser/BlockSource";
    static final String LEGACY_BLOCK_SOURCE = Mc1201Tables.HELPER_PACKAGE + "LegacyBlockSource";
    private static final String MISC = Mc1201Tables.HELPER_PACKAGE + "MiscCompat";
    private static final String LEVEL = "Lnet/minecraft/server/level/ServerLevel;";
    private static final String POS = "Lnet/minecraft/core/BlockPos;";
    private static final String STATE = "Lnet/minecraft/world/level/block/state/BlockState;";
    private static final String BE = "Lnet/minecraft/world/level/block/entity/BlockEntity;";
    private static final String DISPENSER = "Lnet/minecraft/world/level/block/entity/DispenserBlockEntity;";
    private static final String CTOR = "(" + LEVEL + POS + STATE + DISPENSER + ")V";

    private static volatile Set<String> closed;

    /** Access transformer classes (dotted, {@code public-f}) the processed classes need. */
    final Set<String> opened = new TreeSet<>();
    /** Classes that implement a changed interface and could not be converted (another superclass). */
    final Set<String> unconverted = new TreeSet<>();
    int converted;

    /** Applies the shape fixes to a class; returns the number of changes. */
    int apply(ClassNode node) {
        int changes = 0;
        if (node.superName != null && isClosed(node.superName)) opened.add(node.superName.replace('/', '.'));
        if (node.interfaces != null && node.interfaces.contains(BLOCK_SOURCE) && (node.access & Opcodes.ACC_INTERFACE) == 0) {
            if ("java/lang/Object".equals(node.superName)) {
                convertBlockSource(node);
                opened.add(BLOCK_SOURCE.replace('/', '.'));
                converted++;
                changes++;
            } else {
                unconverted.add(node.name.replace('/', '.'));
            }
        }
        return changes;
    }

    static boolean isClosed(String internalName) {
        return closed().contains(internalName);
    }

    private static Set<String> closed() {
        Set<String> c = closed;
        if (c != null) return c;
        synchronized (ClassShape1201.class) {
            if (closed != null) return closed;
            Set<String> set = new HashSet<>();
            try (InputStream raw = ClassShape1201.class.getClassLoader().getResourceAsStream("legacyconnector/forward/1.20.1/mc-closed.txt.gz")) {
                if (raw != null) {
                    BufferedReader r = new BufferedReader(new InputStreamReader(new GZIPInputStream(raw), StandardCharsets.UTF_8));
                    for (String l = r.readLine(); l != null; l = r.readLine()) if (!l.isBlank()) set.add(l.trim());
                }
            } catch (IOException e) {
                throw new IllegalStateException("Corrupt mc-closed.txt.gz", e);
            }
            return closed = set;
        }
    }

    private static void convertBlockSource(ClassNode node) {
        node.interfaces.remove(BLOCK_SOURCE);
        if (!node.interfaces.contains(LEGACY_BLOCK_SOURCE)) node.interfaces.add(LEGACY_BLOCK_SOURCE);
        node.superName = BLOCK_SOURCE;
        for (MethodNode m : node.methods) {
            if (!m.name.equals("<init>") || m.instructions == null) continue;
            for (AbstractInsnNode in = m.instructions.getFirst(); in != null; in = in.getNext()) {
                if (in instanceof MethodInsnNode mi && mi.getOpcode() == Opcodes.INVOKESPECIAL && mi.owner.equals("java/lang/Object") && mi.name.equals("<init>")) {
                    InsnList nulls = new InsnList();
                    for (int i = 0; i < 4; i++) nulls.add(new InsnNode(Opcodes.ACONST_NULL));
                    m.instructions.insertBefore(mi, nulls);
                    mi.owner = BLOCK_SOURCE;
                    mi.desc = CTOR;
                    break;
                }
            }
        }
        bridge(node, "level", "()" + LEVEL, "getLevel", "()" + LEVEL, null);
        bridge(node, "pos", "()" + POS, "getPos", "()" + POS, null);
        bridge(node, "state", "()" + STATE, "getBlockState", "()" + STATE, null);
        bridge(node, "blockEntity", "()" + DISPENSER, "getEntity", "()" + BE, "asDispenser");
        // center(): the record computes it from its own (null) position
        MethodNode center = new MethodNode(Opcodes.ACC_PUBLIC, "center", "()Lnet/minecraft/world/phys/Vec3;", null, null);
        center.instructions.add(new VarInsnNode(Opcodes.ALOAD, 0));
        center.instructions.add(new MethodInsnNode(Opcodes.INVOKEVIRTUAL, node.name, "getPos", "()" + POS, false));
        center.instructions.add(new MethodInsnNode(Opcodes.INVOKESTATIC, MISC, "sourceCenter", "(" + POS + ")Lnet/minecraft/world/phys/Vec3;", false));
        center.instructions.add(new InsnNode(Opcodes.ARETURN));
        center.maxStack = 1;
        center.maxLocals = 1;
        if (!has(node, "center", center.desc)) node.methods.add(center);
    }

    /** {@code name()} of the record answers {@code this.target()}; {@code filter} (a static of MiscCompat taking the answer) narrows the type. */
    private static void bridge(ClassNode node, String name, String desc, String target, String targetDesc, String filter) {
        if (has(node, name, desc)) return;
        MethodNode m = new MethodNode(Opcodes.ACC_PUBLIC, name, desc, null, null);
        m.instructions.add(new VarInsnNode(Opcodes.ALOAD, 0));
        m.instructions.add(new MethodInsnNode(Opcodes.INVOKEVIRTUAL, node.name, target, targetDesc, false));
        if (filter != null) m.instructions.add(new MethodInsnNode(Opcodes.INVOKESTATIC, MISC, filter, "(" + BE + ")" + Type.getReturnType(desc).getDescriptor(), false));
        m.instructions.add(new InsnNode(Opcodes.ARETURN));
        m.maxStack = 1;
        m.maxLocals = 1;
        node.methods.add(m);
    }

    private static boolean has(ClassNode node, String name, String desc) {
        for (MethodNode m : node.methods) if (m.name.equals(name) && m.desc.equals(desc)) return true;
        return false;
    }
}
