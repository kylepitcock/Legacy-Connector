package org.kylepitcock.legacyconnector.v1_7_10.bridge;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;
import legacyconnector.v1_7_10.net.minecraft.world.ChunkPosition;
import legacyconnector.v1_7_10.net.minecraft.world.gen.structure.MapGenStructure;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.CommandEvent;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Structures drawn by legacy {@code MapGenStructure}s are not modern structures, so {@code /locate structure} cannot know
 * them: {@code /locate structure legacyconnector:<name>} (name as the generator calls itself, lower case) asks the legacy
 * generators for their nearest start instead, the way 1.7.10's eye of ender did.
 */
public final class LegacyStructures {
    private static final Logger LOG = LoggerFactory.getLogger("LegacyConnector/Structures");
    private static final Map<MapGenStructure, Boolean> GENERATORS = new WeakHashMap<>();
    private static boolean registered;

    private LegacyStructures() {}

    /** Called from the generator's constructor. */
    public static void track(MapGenStructure generator) {
        synchronized (GENERATORS) {
            GENERATORS.put(generator, Boolean.TRUE);
        }
        register();
    }

    private static synchronized void register() {
        if (registered) return;
        registered = true;
        NeoForge.EVENT_BUS.addListener(LegacyStructures::onCommand);
    }

    private static List<MapGenStructure> generators(String name) {
        List<MapGenStructure> out = new ArrayList<>();
        synchronized (GENERATORS) {
            for (MapGenStructure g : GENERATORS.keySet()) {
                try {
                    if (g.getStructureName().equalsIgnoreCase(name)) out.add(g);
                } catch (RuntimeException | LinkageError e) {
                    // a generator that cannot name itself is not locatable
                }
            }
        }
        return out;
    }

    private static void onCommand(CommandEvent event) {
        String input = event.getParseResults().getReader().getString().trim();
        if (input.startsWith("/")) input = input.substring(1);
        String[] parts = input.split("\\s+");
        if (parts.length < 3 || !parts[0].equals("locate") || !parts[1].equals("structure") || !parts[2].startsWith("legacyconnector:")) return;
        event.setCanceled(true);
        var source = event.getParseResults().getContext().getSource();
        String name = parts[2].substring("legacyconnector:".length());
        ServerLevel level = source.getLevel();
        var gens = generators(name);
        if (gens.isEmpty()) {
            source.sendFailure(Component.literal("No legacy structure called '" + name + "' is generated by the loaded mods"));
            return;
        }
        var world = legacyconnector.v1_7_10.net.minecraft.world.World.mcc$wrap(level);
        int x = (int) source.getPosition().x, y = (int) source.getPosition().y, z = (int) source.getPosition().z;
        ChunkPosition best = null;
        double bestDistance = Double.MAX_VALUE;
        for (MapGenStructure g : gens) {
            try {
                ChunkPosition p = g.getNearestInstance(world, x, y, z);
                if (p == null) continue;
                double d = (double) (p.chunkPosX - x) * (p.chunkPosX - x) + (double) (p.chunkPosZ - z) * (p.chunkPosZ - z);
                if (d < bestDistance) {
                    bestDistance = d;
                    best = p;
                }
            } catch (RuntimeException | LinkageError e) {
                LOG.warn("Locating {} failed: {}", name, e.toString());
            }
        }
        if (best == null) {
            source.sendFailure(Component.literal("Could not find a legacy structure '" + name + "' nearby (only already visited chunks are searched)"));
            return;
        }
        int distance = (int) Math.round(Math.sqrt(bestDistance));
        String message = "The nearest " + name + " is at [" + best.chunkPosX + ", ~, " + best.chunkPosZ + "] (" + distance + " blocks away)";
        source.sendSuccess(() -> Component.literal(message), false);
    }
}
