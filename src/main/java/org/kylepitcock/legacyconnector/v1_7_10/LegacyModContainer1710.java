package org.kylepitcock.legacyconnector.v1_7_10;

import java.io.File;
import java.util.HashMap;
import java.util.Map;
import legacyconnector.v1_7_10.cpw.mods.fml.common.ModContainer;
import legacyconnector.v1_7_10.cpw.mods.fml.common.ModMetadata;
import org.kylepitcock.legacyconnector.core.LegacyModRecord;

/** The legacy-facing ModContainer of a 1.7.10 mod, plus the "currently active mod" used to attribute registrations. */
public final class LegacyModContainer1710 implements ModContainer {
    private static volatile LegacyModContainer1710 active;

    private final LegacyModRecord record;
    private final ModMetadata metadata = new ModMetadata();

    public LegacyModContainer1710(LegacyModRecord record) {
        this.record = record;
        metadata.modId = record.legacyId;
        metadata.name = record.name();
        metadata.version = record.modVersion();
        metadata.autogenerated = record.metadata == null;
    }

    public static LegacyModContainer1710 active() {
        return active;
    }

    static void setActive(LegacyModContainer1710 container) {
        active = container;
    }

    public LegacyModRecord record() {
        return record;
    }

    @Override
    public String getModId() {
        return record.legacyId;
    }

    @Override
    public String getName() {
        return record.name();
    }

    @Override
    public String getVersion() {
        return record.modVersion();
    }

    @Override
    public File getSource() {
        return record.originalFile().toFile();
    }

    @Override
    public ModMetadata getMetadata() {
        return metadata;
    }

    @Override
    public Object getMod() {
        return record.instance;
    }

    @Override
    public String getDisplayVersion() {
        return getVersion();
    }

    @Override
    public Map<String, String> getCustomModProperties() {
        return new HashMap<>();
    }

    @Override
    public String toString() {
        return "LegacyModContainer1710[" + record.legacyId + "]";
    }
}
