package org.kylepitcock.legacyconnector.core.pack;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Supplier;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackType;
import net.neoforged.fml.ModList;
import net.neoforged.fml.loading.FMLPaths;
import org.kylepitcock.legacyconnector.core.LegacyConfig;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Client side of {@link TextureModernizer}: the textures of the translated legacy jars that copy old vanilla art are written
 * to the generated pack (which sits above the mods) in their modern form. A late contributor, so the ore textures
 * {@code OreBackgrounds} rewrote, and anything else generated for the same file, win. Which textures of a jar match is
 * remembered in {@code .legacyconnector/texture-cache} (keyed by the translated jar, whose name carries its content hash,
 * and the fingerprint table), so later starts only read the matching textures. Disable with {@code modernizeTextures = false}.
 */
public final class ModernizedTextures {
    private static final Logger LOG = LoggerFactory.getLogger("LegacyConnector/Textures");
    /** Per translated jar: its classification (survives pack reloads). */
    private static final Map<Path, List<TextureModernizer.Hit>> SCANNED = new ConcurrentHashMap<>();
    /** Generated textures by pack path (a reload, F3+T, writes them again without recomputing). */
    private static final Map<String, byte[]> MADE = new ConcurrentHashMap<>();
    private static volatile boolean logged;

    private ModernizedTextures() {}

    public static void register() {
        GeneratedPack.addLateContributor((type, out) -> {
            if (type == PackType.CLIENT_RESOURCES && LegacyConfig.modernizeTexturesEnabled()) contribute(out);
        });
    }

    private static void contribute(Map<String, Supplier<byte[]>> out) {
        TextureModernizer modernizer = TextureModernizer.get();
        Map<String, byte[]> vanilla = new HashMap<>();
        java.util.function.Function<String, byte[]> modern = name -> vanilla.computeIfAbsent(name, ModernizedTextures::vanillaTexture);
        List<String> summary = new ArrayList<>();
        int[] all = {0, 0};
        for (var file : ModList.get().getModFiles()) {
            Path jar = file.getFile().getFilePath();
            if (!isTranslated(jar)) continue;
            List<TextureModernizer.Hit> hits = SCANNED.computeIfAbsent(jar, j -> scan(modernizer, j));
            if (hits.isEmpty()) continue;
            int exact = 0, base = 0;
            try (ZipFile zip = new ZipFile(jar.toFile())) {
                for (TextureModernizer.Hit hit : hits) {
                    if (out.containsKey(hit.path())) continue; // generated by someone else (ore backgrounds)
                    byte[] png = MADE.get(hit.path());
                    if (png == null) {
                        ZipEntry entry = zip.getEntry(hit.path());
                        if (entry == null) continue;
                        try (InputStream in = zip.getInputStream(entry)) {
                            png = modernizer.apply(hit, in.readAllBytes(), modern);
                        } catch (IOException | RuntimeException e) {
                            png = null;
                        }
                        if (png == null) continue;
                        MADE.put(hit.path(), png);
                    }
                    byte[] made = png;
                    out.put(hit.path(), () -> made);
                    if (hit.kind() == TextureModernizer.Kind.EXACT) exact++;
                    else base++;
                }
            } catch (IOException | RuntimeException e) {
                LOG.debug("Could not read {}", jar, e);
            }
            if (exact + base == 0) continue;
            all[0] += exact;
            all[1] += base;
            String mods = file.getMods().isEmpty() ? jar.getFileName().toString()
                    : String.join(", ", file.getMods().stream().map(m -> m.getModId()).toList());
            summary.add(mods + ": modernized " + (exact + base) + " textures (" + exact + " exact copies, " + base + " backgrounds)");
        }
        if (!logged) {
            logged = true;
            for (String line : summary) LOG.info(line);
            LOG.info("Old vanilla art in legacy textures: {} exact copies and {} backgrounds replaced by the modern textures (modernizeTextures = false keeps them)",
                    all[0], all[1]);
        }
    }

    /** The translated legacy jars ({@code .legacyconnector/cache/<name>-<hash>.jar}), not the runtime or the synthesized API. */
    private static boolean isTranslated(Path jar) {
        if (jar == null || jar.getParent() == null || jar.getParent().getParent() == null) return false;
        String name = jar.getFileName().toString();
        return jar.getParent().getFileName().toString().equals("cache") && jar.getParent().getParent().getFileName().toString().equals(".legacyconnector")
                && name.endsWith(".jar") && !name.startsWith("legacyconnector-") && Files.isRegularFile(jar);
    }

    private static List<TextureModernizer.Hit> scan(TextureModernizer modernizer, Path jar) {
        Path cache = null;
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            md.update((jar.getFileName() + "|" + Files.size(jar) + "|" + Files.getLastModifiedTime(jar).toMillis() + "|" + modernizer.key())
                    .getBytes(StandardCharsets.UTF_8));
            String key = java.util.HexFormat.of().formatHex(md.digest()).substring(0, 24);
            Path dir = FMLPaths.GAMEDIR.get().resolve(".legacyconnector").resolve("texture-cache");
            cache = dir.resolve(key + ".txt");
            if (Files.isRegularFile(cache)) {
                List<TextureModernizer.Hit> hits = new ArrayList<>();
                for (String line : Files.readAllLines(cache, StandardCharsets.UTF_8)) {
                    String[] p = line.split("\t");
                    if (p.length >= 3) hits.add(new TextureModernizer.Hit(p[1], TextureModernizer.Kind.valueOf(p[0]), p[2], p.length > 3 ? p[3] : null));
                }
                return hits;
            }
        } catch (IOException | RuntimeException | java.security.NoSuchAlgorithmException e) {
            // scan again
        }
        List<TextureModernizer.Hit> hits;
        try (ZipFile zip = new ZipFile(jar.toFile())) {
            hits = modernizer.scan(zip);
        } catch (IOException | RuntimeException e) {
            return List.of();
        }
        if (cache != null) {
            StringBuilder text = new StringBuilder();
            for (TextureModernizer.Hit h : hits) {
                text.append(h.kind()).append('\t').append(h.path()).append('\t').append(h.modern());
                if (h.base() != null) text.append('\t').append(h.base());
                text.append('\n');
            }
            try {
                Files.createDirectories(cache.getParent());
                Files.writeString(cache, text);
            } catch (IOException e) {
                // classified again next start
            }
        }
        return hits;
    }

    /** A texture of the vanilla pack ({@code block/stone}), not of resource packs: the fingerprints are vanilla's. */
    private static byte[] vanillaTexture(String name) {
        try {
            var id = ResourceLocation.fromNamespaceAndPath("minecraft", "textures/" + name + ".png");
            var resource = net.minecraft.client.Minecraft.getInstance().getVanillaPackResources().getResource(PackType.CLIENT_RESOURCES, id);
            if (resource == null) return null;
            try (InputStream in = resource.get()) {
                return in.readAllBytes();
            }
        } catch (IOException | RuntimeException e) {
            return null;
        }
    }
}
