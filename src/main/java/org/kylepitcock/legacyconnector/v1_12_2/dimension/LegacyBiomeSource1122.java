package org.kylepitcock.legacyconnector.v1_12_2.dimension;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.stream.Stream;
import legacyconnector.v1_12_2.net.minecraft.util.math.BlockPos;
import legacyconnector.v1_12_2.net.minecraft.world.World;
import legacyconnector.v1_12_2.net.minecraft.world.biome.BiomeProvider;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderSet;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.biome.Climate;
import org.kylepitcock.legacyconnector.v1_12_2.bridge.BiomeBridge1122;
import org.kylepitcock.legacyconnector.v1_12_2.bridge.WorldBridge1122;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Biomes of a 1.12.2 mod dimension: the {@code BiomeProvider} of the dimension's world provider, asked for the biome in the middle of
 * each 4x4 column and mapped to the modern biome of the legacy one ({@code BiomeBridge1122.modernId}; mod biomes are generated by
 * {@code LegacyBiomes1122}). Answers are cached per column; a provider that is not ready or throws gives the fallback biome.
 */
public class LegacyBiomeSource1122 extends BiomeSource {
    private static final Logger LOG = LoggerFactory.getLogger("LegacyConnector/Biomes1122");
    public static final MapCodec<LegacyBiomeSource1122> CODEC = RecordCodecBuilder.mapCodec(i -> i.group(
            Codec.INT.fieldOf("dimension").forGetter(s -> s.dimension),
            Biome.LIST_CODEC.fieldOf("biomes").forGetter(s -> s.biomes)).apply(i, LegacyBiomeSource1122::new));

    private static final int CACHE_LIMIT = 1 << 16;
    private static final java.util.concurrent.atomic.AtomicInteger FAILURES = new java.util.concurrent.atomic.AtomicInteger();

    private static final ThreadLocal<Boolean> ASKING = new ThreadLocal<>();

    private final int dimension;
    private final HolderSet<Biome> biomes;
    private volatile Map<ResourceLocation, Holder<Biome>> byKey;
    private volatile Holder<Biome> fallback;
    private volatile BiomeProvider provider;
    private final Map<Long, Holder<Biome>> columns = new ConcurrentHashMap<>();
    private final Map<legacyconnector.v1_12_2.net.minecraft.world.biome.Biome, Holder<Biome>> byLegacy = new ConcurrentHashMap<>();

    public LegacyBiomeSource1122(int dimension, HolderSet<Biome> biomes) {
        this.dimension = dimension;
        this.biomes = biomes;
    }

    @Override
    protected MapCodec<? extends BiomeSource> codec() {
        return CODEC;
    }

    @Override
    protected Stream<Holder<Biome>> collectPossibleBiomes() {
        return biomes.stream();
    }

    private static final java.util.concurrent.atomic.AtomicInteger WHY = new java.util.concurrent.atomic.AtomicInteger();

    /** Says (first 5 times) why the fallback biome was answered. */
    private void why(String reason) {
        if (WHY.incrementAndGet() <= 5) LOG.warn("1.12.2 dimension {}: fallback biome (plains) answered: {}", dimension, reason);
    }

    private Map<ResourceLocation, Holder<Biome>> byKey() {
        Map<ResourceLocation, Holder<Biome>> map = byKey;
        if (map == null) {
            final Map<ResourceLocation, Holder<Biome>> target = new HashMap<>();
            for (Holder<Biome> h : biomes) h.unwrapKey().ifPresent(k -> target.put(k.location(), h));
            byKey = map = target;
        }
        return map;
    }

    private Holder<Biome> fallback() {
        Holder<Biome> f = fallback;
        if (f == null) {
            f = byKey().get(ResourceLocation.withDefaultNamespace("plains"));
            if (f == null) f = biomes.stream().findFirst().orElseThrow();
            fallback = f;
        }
        return f;
    }

    private Holder<Biome> holderOf(legacyconnector.v1_12_2.net.minecraft.world.biome.Biome biome) {
        Holder<Biome> h = byLegacy.get(biome);
        if (h == null) {
            ResourceLocation id = BiomeBridge1122.modernId(biome);
            h = byKey().get(id);
            if (h == null) {
                why("the legacy biome " + biome.getClass().getName() + " maps to " + id + ", which is not in this dimension's biome list");
                h = fallback();
            }
            byLegacy.put(biome, h);
        }
        return h;
    }

    private BiomeProvider provider() {
        BiomeProvider p = provider;
        if (p == null) {
            var server = net.neoforged.neoforge.server.ServerLifecycleHooks.getCurrentServer();
            var level = server == null ? null : server.getLevel(Dimensions1122.levelKey(dimension));
            if (level == null) return null;
            try {
                p = World.mcc$get$provider(WorldBridge1122.wrap(level)).getBiomeProvider();
            } catch (RuntimeException | LinkageError e) {
                int n = FAILURES.incrementAndGet();
                if (n <= 3) LOG.error("The biome provider of 1.12.2 dimension {} could not be created", dimension, e);
                return null;
            }
            provider = p;
        }
        return p;
    }

    @Override
    public Holder<Biome> getNoiseBiome(int qx, int qy, int qz, Climate.Sampler sampler) {
        long key = ((long) qx << 32) ^ (qz & 0xFFFFFFFFL);
        Holder<Biome> cached = columns.get(key);
        if (cached != null) return cached;
        BiomeProvider p = provider();
        if (p == null) { // the level does not exist yet: not cached
            why("no provider/level yet (level missing or the provider could not be created)");
            return fallback();
        }
        // a provider without layers of its own (the shim's world-backed one) asks this source back: answer plains instead of recursing
        if (ASKING.get() != null) {
            why("recursive ask: the provider answered from the world's own biome source");
            return fallback();
        }
        legacyconnector.v1_12_2.net.minecraft.world.biome.Biome biome;
        ASKING.set(Boolean.TRUE);
        try {
            synchronized (p) { // legacy layers and their cache keep per-call state
                biome = p.getBiome(new BlockPos((qx << 2) + 2, 0, (qz << 2) + 2));
            }
        } catch (RuntimeException | LinkageError e) {
            int n = FAILURES.incrementAndGet();
            if (n <= 3 || n % 500 == 0) LOG.error("The biome provider of 1.12.2 dimension {} failed at {},{} ({} failures so far)", dimension, qx << 2, qz << 2, n, e);
            why("the provider " + p.getClass().getName() + " threw " + e);
            return fallback(); // a broken provider must not take the server down; not cached
        } finally {
            ASKING.remove();
        }
        if (biome == null) why("the provider " + p.getClass().getName() + " returned no biome at " + (qx << 2) + "," + (qz << 2));
        Holder<Biome> h = biome == null ? fallback() : holderOf(biome);
        if (columns.size() >= CACHE_LIMIT) columns.clear();
        columns.put(key, h);
        return h;
    }
}
