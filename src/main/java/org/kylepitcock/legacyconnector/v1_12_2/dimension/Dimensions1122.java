package org.kylepitcock.legacyconnector.v1_12_2.dimension;

import com.google.gson.JsonObject;
import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.function.Supplier;
import legacyconnector.v1_12_2.net.minecraft.world.DimensionType;
import legacyconnector.v1_12_2.net.minecraft.world.WorldProvider;
import legacyconnector.v1_12_2.net.minecraftforge.common.DimensionManager;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.Level;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Mod dimensions of 1.12.2. A {@code DimensionManager.registerDimension(id, type)} of a type whose provider is a mod's class becomes
 * the modern dimension {@code legacyconnector:dim_<id>} (data pack entries generated here), generated by
 * {@link LegacyChunkGenerator1122} from the provider's {@code createChunkGenerator()}.
 */
public final class Dimensions1122 {
    private static final Logger LOG = LoggerFactory.getLogger("LegacyConnector/Dimensions");
    private static final String NAMESPACE = "legacyconnector";
    private static final String PREFIX = "dim_";

    private Dimensions1122() {}

    public static ResourceLocation id(int dimension) {
        return ResourceLocation.fromNamespaceAndPath(NAMESPACE, PREFIX + dimension);
    }

    public static ResourceKey<Level> levelKey(int dimension) {
        return ResourceKey.create(Registries.DIMENSION, id(dimension));
    }

    /** The legacy dimension id of a {@code legacyconnector:dim_<id>} location, or null. */
    public static Integer idOf(ResourceLocation location) {
        if (location == null || !NAMESPACE.equals(location.getNamespace()) || !location.getPath().startsWith(PREFIX)) return null;
        try {
            return Integer.parseInt(location.getPath().substring(PREFIX.length()));
        } catch (NumberFormatException e) {
            return null;
        }
    }

    /** The mod dimensions: registered ids whose type has a provider class of a mod. */
    public static Map<Integer, DimensionType> modDimensions() {
        Map<Integer, DimensionType> out = new java.util.TreeMap<>();
        for (int id : DimensionManager.getIDs()) {
            if (id >= -1 && id <= 1) continue;
            DimensionType type = DimensionManager.getProviderType(id);
            if (type != null && type.mcc$providerClass() != null) out.put(id, type);
        }
        return out;
    }

    /** A new provider of a mod dimension, with its id set (null if its class cannot be built). */
    public static WorldProvider newProvider(int id) {
        try {
            return DimensionManager.createProviderFor(id);
        } catch (RuntimeException | LinkageError e) {
            LOG.error("Could not create the world provider of dimension {}", id, e);
            return null;
        }
    }

    /** Data pack entries of every mod dimension registered by the end of legacy loading. */
    public static void contribute(Map<String, Supplier<byte[]>> out) {
        for (var e : modDimensions().entrySet()) {
            int id = e.getKey();
            boolean sky = true;
            try {
                var ctor = e.getValue().mcc$providerClass().getDeclaredConstructor();
                ctor.setAccessible(true);
                sky = ((WorldProvider) ctor.newInstance()).hasSkyLight();
            } catch (ReflectiveOperationException | RuntimeException | LinkageError ex) {
                // keep the overworld-like default
            }
            JsonObject type = new JsonObject();
            type.addProperty("ultrawarm", false);
            type.addProperty("natural", true);
            type.addProperty("coordinate_scale", 1.0);
            type.addProperty("has_skylight", sky);
            type.addProperty("has_ceiling", false);
            type.addProperty("ambient_light", 0.0F);
            type.addProperty("monster_spawn_light_level", 7);
            type.addProperty("monster_spawn_block_light_limit", 0);
            type.addProperty("piglin_safe", false);
            type.addProperty("bed_works", true);
            type.addProperty("respawn_anchor_works", false);
            type.addProperty("has_raids", false);
            type.addProperty("logical_height", 256);
            type.addProperty("min_y", 0);
            type.addProperty("height", 256);
            type.addProperty("infiniburn", "#minecraft:infiniburn_overworld");
            type.addProperty("effects", "minecraft:overworld");
            byte[] typeBytes = type.toString().getBytes(StandardCharsets.UTF_8);
            String name = PREFIX + id;
            out.put("data/" + NAMESPACE + "/dimension_type/" + name + ".json", () -> typeBytes);

            JsonObject biomeSource = new JsonObject();
            biomeSource.addProperty("type", "minecraft:fixed");
            biomeSource.addProperty("biome", "minecraft:plains");
            JsonObject generator = new JsonObject();
            generator.addProperty("type", NAMESPACE + ":legacy_1122");
            generator.addProperty("dimension", id);
            generator.add("biome_source", biomeSource);
            JsonObject stem = new JsonObject();
            stem.addProperty("type", NAMESPACE + ":" + name);
            stem.add("generator", generator);
            byte[] stemBytes = stem.toString().getBytes(StandardCharsets.UTF_8);
            out.put("data/" + NAMESPACE + "/dimension/" + name + ".json", () -> stemBytes);
            LOG.info("1.12.2 mod dimension {} ({}, {}) is available as {}:{}", id, e.getValue().getName(), e.getValue().mcc$providerClass().getName(), NAMESPACE, name);
        }
    }

    /** Development check ({@code -Dlegacyconnector.entitySelfTest=true}): generates an area of every mod dimension and counts blocks. */
    public static void registerSelfTest() {
        if (!Boolean.getBoolean("legacyconnector.entitySelfTest")) return;
        net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener((net.neoforged.neoforge.event.server.ServerStartedEvent e) -> selfTest(e.getServer()));
    }

    private static void selfTest(net.minecraft.server.MinecraftServer server) {
        for (int id : modDimensions().keySet()) {
            var level = server.getLevel(levelKey(id));
            if (level == null) {
                LOG.info("1.12.2 dimension {}: no level", id);
                continue;
            }
            long start = System.nanoTime();
            int solid = 0;
            Map<String, Integer> byNamespace = new java.util.TreeMap<>();
            try {
                var pos = new net.minecraft.core.BlockPos.MutableBlockPos();
                int rad = Integer.getInteger("legacyconnector.dimTestRadius", 2);
                for (int cx = -rad; cx <= rad; cx++) {
                    for (int cz = -rad; cz <= rad; cz++) {
                        var chunk = level.getChunk(cx, cz);
                        for (int x = 0; x < 16; x++) {
                            for (int z = 0; z < 16; z++) {
                                for (int y = 0; y < 256; y++) {
                                    var state = chunk.getBlockState(pos.set(x, y, z));
                                    if (state.isAir()) continue;
                                    solid++;
                                    byNamespace.merge(net.minecraft.core.registries.BuiltInRegistries.BLOCK.getKey(state.getBlock()).getNamespace(), 1, Integer::sum);
                                }
                            }
                        }
                    }
                }
                var provider = legacyconnector.v1_12_2.net.minecraft.world.World.mcc$get$provider(
                        org.kylepitcock.legacyconnector.v1_12_2.bridge.WorldBridge1122.wrap(level));
                LOG.info("1.12.2 dimension {} provider {}: skyLight={} surface={} cloudHeight={} id={} reachable={}", id, provider.getClass().getName(),
                        provider.hasSkyLight(), provider.isSurfaceWorld(), provider.getCloudHeight(), provider.getDimension(),
                        org.kylepitcock.legacyconnector.v1_12_2.bridge.EntityBridge1122.level(server, id) == level);
                final int radF = rad;
                server.execute(() -> server.execute(() -> {
                int tiles = 0, loot = 0;
                for (int cx = -radF - 4; cx <= radF + 4; cx++) {
                    for (int cz = -radF - 4; cz <= radF + 4; cz++) {
                        var loaded = level.getChunkSource().getChunkNow(cx, cz);
                        if (loaded == null) continue;
                        for (var be : loaded.getBlockEntities().values()) {
                            if (!(be instanceof org.kylepitcock.legacyconnector.v1_12_2.adapter.Legacy1122BlockEntity) && !(be instanceof net.minecraft.world.level.block.entity.ChestBlockEntity)) continue;
                            tiles++;
                            String nbt = be.saveWithoutMetadata(level.registryAccess()).toString();
                            if (nbt.contains("LootTable") || nbt.contains("Items:[{") || nbt.contains("Items\":[{")) loot++;
                        }
                    }
                }
                LOG.info("1.12.2 dimension {}: {} legacy tile entities in the generated chunks, {} with loot (loot table or items)", id, tiles, loot);
                }));
                LOG.info("1.12.2 dimension {} generated {} non-air blocks {} in {} ms", id, solid, byNamespace, (System.nanoTime() - start) / 1_000_000);
            } catch (RuntimeException | LinkageError ex) {
                LOG.error("1.12.2 dimension {} failed to generate", id, ex);
            }
        }
    }
}
