package org.kylepitcock.legacyconnector.v1_12_2.bridge;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.Supplier;
import legacyconnector.v1_12_2.net.minecraft.world.WorldType;
import org.kylepitcock.legacyconnector.core.worldgen.LegacyWorldPresetPack;

/**
 * 1.12.2 mod world types (Forge's {@code new WorldType(name)}: Botania's skyblock, Lost Cities, TerraFirmaCraft, Biomes O' Plenty, ...) as
 * 1.21 world presets listed on the Create World screen ({@link LegacyWorldPresetPack}). A world created with one reports the type through
 * {@code World.getWorldType()} ({@code WorldType.mcc$of}), so mods keyed on it (skyblock islands, ...) see their own type.
 */
public final class LegacyWorldPresets1122 {
    private LegacyWorldPresets1122() {}

    /** World types registered by legacy mods that can be created. */
    public static List<WorldType> modTypes() {
        List<WorldType> out = new ArrayList<>();
        for (WorldType t : WorldType.WORLD_TYPES) if (t != null && t.mcc$owner != null && t.canBeCreated()) out.add(t);
        return out;
    }

    /**
     * True when the type brings its own terrain generator ({@code getChunkGenerator} overridden): worlds of the type are generated by the mod's
     * generator, hosted as the overworld ({@code legacyconnector:legacy_1122}, dimension 0), with the type's biome provider.
     */
    public static boolean hasOwnGenerator(WorldType t) {
        if (t == null || t.mcc$owner == null) return false;
        try {
            return t.getClass().getMethod("getChunkGenerator", legacyconnector.v1_12_2.net.minecraft.world.World.class, String.class)
                    .getDeclaringClass() != WorldType.class;
        } catch (ReflectiveOperationException | LinkageError e) {
            return false;
        }
    }

    /** True when the type overrides {@code getBiomeProvider} (the base answers the world's own provider). */
    public static boolean hasOwnBiomeProvider(WorldType t) {
        if (t == null) return false;
        try {
            return t.getClass().getMethod("getBiomeProvider", legacyconnector.v1_12_2.net.minecraft.world.World.class).getDeclaringClass() != WorldType.class;
        } catch (ReflectiveOperationException | LinkageError e) {
            return false;
        }
    }

    private static List<LegacyWorldPresetPack.Preset> presets() {
        List<LegacyWorldPresetPack.Preset> out = new ArrayList<>();
        for (WorldType t : modTypes()) {
            JsonObject generator = null;
            if (hasOwnGenerator(t)) {
                JsonObject source = new JsonObject();
                source.addProperty("type", "legacyconnector:legacy_1122");
                source.addProperty("dimension", 0);
                JsonArray biomes = new JsonArray();
                org.kylepitcock.legacyconnector.v1_12_2.dimension.Dimensions1122.providerBiomeIds().forEach(biomes::add);
                source.add("biomes", biomes);
                generator = new JsonObject();
                generator.addProperty("type", "legacyconnector:legacy_1122");
                generator.addProperty("dimension", 0);
                generator.addProperty("world_type", t.getName());
                // (a type without a biome provider of its own gets 1.12's vanilla layers as its provider, see WorldProvider.init: the modern
                // multi-noise sampler is not available to a generator that is not the noise one)
                generator.add("biome_source", source);
            }
            out.add(new LegacyWorldPresetPack.Preset(t.mcc$presetId(), t.getName(), t.mcc$owner, t.getTranslationKey(), generator));
        }
        return out;
    }

    public static void contribute(Map<String, Supplier<byte[]>> out) {
        LegacyWorldPresetPack.contribute(out, presets());
    }

    /** Button names: the mod's own translation of {@code generator.<name>}, else the type name. */
    public static void registerNames() {
        LegacyWorldPresetPack.registerNames(presets());
    }
}
