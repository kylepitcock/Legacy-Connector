package legacyconnector.v1_7_10.net.minecraft.world;

import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.Level;

/**
 * Dimension facts. 1.7.10 numeric dimension ids: 0 overworld, -1 nether, 1 end, others hashed. Mods subclass it
 * for their own dimensions (no-arg constructor + {@link #setDimension}); those are not registered as modern
 * dimensions yet, but the classes load and their logic can be called.
 */
public class WorldProvider {
    public int dimensionId;
    public boolean hasNoSky;
    public boolean isHellWorld;
    public World worldObj;
    public WorldType terrainType = WorldType.DEFAULT;
    /** The generator options of the world type (1.7.10: field_82913_c). */
    public String field_82913_c = "";
    /** The biome provider of this dimension (mods assign it in registerWorldChunkManager). */
    public legacyconnector.v1_7_10.net.minecraft.world.biome.WorldChunkManager worldChunkMgr;
    private String mcc$name;
    /** Light level to brightness (1.7.10: filled by {@link #generateLightBrightnessTable}; mods override that to light their dimension). */
    public float[] lightBrightnessTable = new float[16];

    public WorldProvider() {
        this.mcc$name = getClass().getSimpleName();
    }

    /** Whether it is day here (dimensions without a day cycle override it). */
    public boolean isDaytime() {
        return worldObj == null || worldObj.isDaytime();
    }

    public final void registerWorld(World world) {
        this.worldObj = world;
        try {
            var info = world.getWorldInfo();
            if (info != null && info.getTerrainType() != null) this.terrainType = info.getTerrainType();
            if (info != null && info.getGeneratorOptions() != null) this.field_82913_c = info.getGeneratorOptions();
        } catch (RuntimeException | LinkageError ignored) {
            // generation regions have no world info yet: the default world type applies
        }
        registerWorldChunkManager();
        generateLightBrightnessTable();
    }

    protected void registerWorldChunkManager() {
    }

    /** 1.7.10's curve with no ambient light (the nether used 0.1); index 0 is the brightness of complete darkness. */
    protected void generateLightBrightnessTable() {
        float ambient = dimensionId == -1 ? 0.1F : 0.0F;
        for (int i = 0; i <= 15; i++) {
            float f = 1.0F - i / 15.0F;
            lightBrightnessTable[i] = (1.0F - f) / (f * 3.0F + 1.0F) * (1.0F - ambient) + ambient;
        }
    }

    /**
     * The dimension's ambient light as a modern dimension type states it: the brightness at light 0 of the provider's table
     * (1.7.10's curve is the modern one, lifted by the ambient level). Witchery's mirror world lifts it to 0.1 like the nether.
     */
    public float mcc$ambientLight() {
        try {
            generateLightBrightnessTable();
            float a = lightBrightnessTable != null && lightBrightnessTable.length > 0 ? lightBrightnessTable[0] : 0.0F;
            return Float.isFinite(a) ? Math.max(0.0F, Math.min(1.0F, a)) : 0.0F;
        } catch (RuntimeException | LinkageError e) {
            return 0.0F;
        }
    }

    /** The chunk generator of the dimension (null: the dimension is generated by the default terrain). */
    public legacyconnector.v1_7_10.net.minecraft.world.chunk.IChunkProvider createChunkGenerator() {
        return worldObj == null ? null : terrainType.getChunkGenerator(worldObj, field_82913_c);
    }

    public void setDimension(int dim) {
        this.dimensionId = dim;
    }

    public WorldProvider(ResourceKey<Level> key, boolean hasSkyLight, boolean ultraWarm) {
        this.dimensionId = dimensionId(key);
        this.hasNoSky = !hasSkyLight;
        this.isHellWorld = ultraWarm;
        this.mcc$name = key.location().getPath();
        generateLightBrightnessTable();
    }

    public static int dimensionId(ResourceKey<Level> key) {
        if (key == Level.OVERWORLD) return 0;
        if (key == Level.NETHER) return -1;
        if (key == Level.END) return 1;
        Integer legacy = org.kylepitcock.legacyconnector.v1_7_10.dimension.LegacyDimensions.idOf(key.location());
        if (legacy != null) return legacy;
        return 2 + Math.floorMod(key.location().toString().hashCode(), 1 << 20);
    }

    public String getDimensionName() {
        return switch (dimensionId) {
            case 0 -> "Overworld";
            case -1 -> "Nether";
            case 1 -> "The End";
            default -> mcc$name;
        };
    }

    /** 1.7.10: true unless overridden (the nether and the end said false); also decides whether sky and clouds are drawn. */
    public boolean isSurfaceWorld() {
        return dimensionId != -1 && dimensionId != 1;
    }

    public boolean canRespawnHere() {
        return dimensionId == 0;
    }

    public int getAverageGroundLevel() {
        return 64;
    }

    public int getActualHeight() {
        return hasNoSky ? 128 : 256;
    }

    // ------------------------------------------------------------------ client: sky, fog and clouds (see LegacyDimensionEffects)

    private legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler mcc$skyRenderer;
    private legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler mcc$cloudRenderer;
    private legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler mcc$weatherRenderer;

    public legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler getSkyRenderer() {
        return mcc$skyRenderer;
    }

    public void setSkyRenderer(legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler renderer) {
        this.mcc$skyRenderer = renderer;
    }

    public legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler getCloudRenderer() {
        return mcc$cloudRenderer;
    }

    public void setCloudRenderer(legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler renderer) {
        this.mcc$cloudRenderer = renderer;
    }

    public legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler getWeatherRenderer() {
        return mcc$weatherRenderer;
    }

    public void setWeatherRenderer(legacyconnector.v1_7_10.net.minecraftforge.client.IRenderHandler renderer) {
        this.mcc$weatherRenderer = renderer;
    }

    /** The time of day as a 0..1 angle (vanilla's curve: the sun lingers near the horizon). */
    public float calculateCelestialAngle(long worldTime, float partialTicks) {
        int i = (int) (worldTime % 24000L);
        float f1 = ((float) i + partialTicks) / 24000.0F - 0.25F;
        if (f1 < 0.0F) f1 += 1.0F;
        if (f1 > 1.0F) f1 -= 1.0F;
        float f2 = f1;
        f1 = 1.0F - (float) ((Math.cos((double) f1 * Math.PI) + 1.0D) / 2.0D);
        return f2 + (f1 - f2) / 3.0F;
    }

    public int getMoonPhase(long worldTime) {
        return (int) (worldTime / 24000L % 8L + 8L) % 8;
    }

    /** Vanilla's fog colour for a time of day: pale blue-grey, darker at night. */
    public legacyconnector.v1_7_10.net.minecraft.util.Vec3 getFogColor(float celestialAngle, float partialTicks) {
        float f = (float) Math.cos(celestialAngle * (float) Math.PI * 2.0F) * 2.0F + 0.5F;
        f = Math.max(0.0F, Math.min(1.0F, f));
        float r = 0.7529412F * (f * 0.94F + 0.06F);
        float g = 0.84705883F * (f * 0.94F + 0.06F);
        float b = 1.0F * (f * 0.91F + 0.09F);
        return legacyconnector.v1_7_10.net.minecraft.util.Vec3.createVectorHelper(r, g, b);
    }

    /** How many blocks of this dimension one block of the overworld is when travelling through a portal (the nether is 8). */
    public double getMovementFactor() {
        return dimensionId == -1 ? 8.0D : 1.0D;
    }

    public long getSeed() {
        return worldObj == null ? 0L : worldObj.getSeed();
    }

    public long getWorldTime() {
        return worldObj == null ? 0L : worldObj.getWorldTime();
    }

    public int getHeight() {
        return 256;
    }

    public float[] calcSunriseSunsetColors(float celestialAngle, float partialTicks) {
        float f2 = (float) Math.cos(celestialAngle * (float) Math.PI * 2.0F);
        if (f2 >= -0.4F && f2 <= 0.4F) {
            float f3 = f2 / 0.4F * 0.5F + 0.5F;
            float f4 = 1.0F - (1.0F - (float) Math.sin(f3 * (float) Math.PI)) * 0.99F;
            f4 *= f4;
            return new float[] {f3 * 0.3F + 0.7F, f3 * f3 * 0.7F + 0.2F, f3 * f3 * 0.0F + 0.2F, f4};
        }
        return null;
    }

    public boolean isSkyColored() {
        return true;
    }

    public float getCloudHeight() {
        return 128.0F;
    }

    public boolean doesXZShowFog(int x, int z) {
        return false;
    }

    public double getVoidFogYFactor() {
        return 0.03125D;
    }

    public String getSaveFolder() {
        return dimensionId == 0 ? null : "DIM" + dimensionId;
    }

    public void updateWeather() {
        if (worldObj != null) worldObj.updateWeatherBody();
    }

    // ------------------------------------------------------------------ Forge's provider hooks: the defaults ask the world's *Body methods

    /** A new provider for a dimension id (the registered provider class of that dimension). */
    public static WorldProvider getProviderForDimension(int dimension) {
        return legacyconnector.v1_7_10.net.minecraftforge.common.DimensionManager.createProviderFor(dimension);
    }

    public legacyconnector.v1_7_10.net.minecraft.util.Vec3 getSkyColor(legacyconnector.v1_7_10.net.minecraft.entity.Entity entity, float partialTicks) {
        return worldObj == null ? legacyconnector.v1_7_10.net.minecraft.util.Vec3.createVectorHelper(0.47D, 0.65D, 1.0D)
                : worldObj.getSkyColorBody(entity, partialTicks);
    }

    public legacyconnector.v1_7_10.net.minecraft.util.Vec3 drawClouds(float partialTicks) {
        return worldObj == null ? legacyconnector.v1_7_10.net.minecraft.util.Vec3.createVectorHelper(1.0D, 1.0D, 1.0D) : worldObj.drawCloudsBody(partialTicks);
    }

    public float getStarBrightness(float partialTicks) {
        return worldObj == null ? 0.0F : worldObj.getStarBrightnessBody(partialTicks);
    }

    public float getSunBrightness(float partialTicks) {
        return worldObj == null ? 1.0F : worldObj.getSunBrightnessBody(partialTicks);
    }

    /** The height the horizon is drawn at: the world type's (63, flat worlds 0). */
    public double getHorizon() {
        return terrainType == null ? 63.0D : terrainType.getHorizon(worldObj);
    }

    public legacyconnector.v1_7_10.net.minecraft.world.biome.BiomeGenBase getBiomeGenForCoords(int x, int z) {
        return worldObj == null ? legacyconnector.v1_7_10.net.minecraft.world.biome.BiomeGenBase.plains : worldObj.getBiomeGenForCoordsBody(x, z);
    }

    public boolean isBlockHighHumidity(int x, int y, int z) {
        var biome = getBiomeGenForCoords(x, z);
        return biome != null && biome.isHighHumidity();
    }

    public boolean canBlockFreeze(int x, int y, int z, boolean byWater) {
        return worldObj != null && worldObj.canBlockFreezeBody(x, y, z, byWater);
    }

    public boolean canSnowAt(int x, int y, int z, boolean checkLight) {
        return worldObj != null && worldObj.canSnowAtBody(x, y, z, checkLight);
    }

    public boolean canMineBlock(legacyconnector.v1_7_10.net.minecraft.entity.player.EntityPlayer player, int x, int y, int z) {
        return worldObj == null || worldObj.canMineBlockBody(player, x, y, z);
    }

    public void calculateInitialWeather() {
        if (worldObj != null) worldObj.calculateInitialWeatherBody();
    }

    /** Clears the weather (sleeping through the night). */
    public void resetRainAndThunder() {
        if (worldObj == null) return;
        var info = worldObj.getWorldInfo();
        info.setRainTime(0);
        info.setRaining(false);
        info.setThunderTime(0);
        info.setThundering(false);
    }

    /** Sets the time of day of this dimension's world. */
    public void setWorldTime(long time) {
        if (worldObj != null) worldObj.getWorldInfo().setWorldTime(time);
    }

    /** Where entities arrive from the end portal (the obsidian platform of the End; none elsewhere). */
    public legacyconnector.v1_7_10.net.minecraft.util.ChunkCoordinates getEntrancePortalLocation() {
        return dimensionId == 1 ? new legacyconnector.v1_7_10.net.minecraft.util.ChunkCoordinates(100, 50, 0) : null;
    }
}
