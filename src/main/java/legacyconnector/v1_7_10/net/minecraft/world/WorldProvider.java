package legacyconnector.v1_7_10.net.minecraft.world;

import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.Level;

/**
 * Dimension facts. 1.7.10 numeric dimension ids: 0 overworld, -1 nether, 1 end, others hashed. Mods subclass it
 * for their own dimensions (no-arg constructor + {@link #setDimension}); those are not registered as modern
 * dimensions yet, but the classes load and their logic can be called.
 */
public class WorldProvider {
    public int dimensionId;
    public boolean hasNoSky;
    public boolean isHellWorld;
    public World worldObj;
    public String terrainType;
    /** The biome provider of this dimension (mods assign it in registerWorldChunkManager). */
    public legacyconnector.v1_7_10.net.minecraft.world.biome.WorldChunkManager worldChunkMgr;
    private String mcc$name;

    public WorldProvider() {
        this.mcc$name = getClass().getSimpleName();
    }

    public final void registerWorld(World world) {
        this.worldObj = world;
        registerWorldChunkManager();
    }

    protected void registerWorldChunkManager() {
    }

    /** The chunk generator of the dimension (null: the dimension is generated by the default terrain). */
    public legacyconnector.v1_7_10.net.minecraft.world.chunk.IChunkProvider createChunkGenerator() {
        return null;
    }

    public void setDimension(int dim) {
        this.dimensionId = dim;
    }

    public WorldProvider(ResourceKey<Level> key, boolean hasSkyLight, boolean ultraWarm) {
        this.dimensionId = dimensionId(key);
        this.hasNoSky = !hasSkyLight;
        this.isHellWorld = ultraWarm;
        this.mcc$name = key.location().getPath();
    }

    public static int dimensionId(ResourceKey<Level> key) {
        if (key == Level.OVERWORLD) return 0;
        if (key == Level.NETHER) return -1;
        if (key == Level.END) return 1;
        Integer legacy = org.kylepitcock.legacyconnector.v1_7_10.dimension.LegacyDimensions.idOf(key.location());
        if (legacy != null) return legacy;
        return 2 + Math.floorMod(key.location().toString().hashCode(), 1 << 20);
    }

    public String getDimensionName() {
        return switch (dimensionId) {
            case 0 -> "Overworld";
            case -1 -> "Nether";
            case 1 -> "The End";
            default -> mcc$name;
        };
    }

    public boolean isSurfaceWorld() {
        return dimensionId == 0;
    }

    public boolean canRespawnHere() {
        return dimensionId == 0;
    }

    public int getAverageGroundLevel() {
        return 64;
    }

    public int getActualHeight() {
        return hasNoSky ? 128 : 256;
    }

    public String getSaveFolder() {
        return dimensionId == 0 ? null : "DIM" + dimensionId;
    }
}
