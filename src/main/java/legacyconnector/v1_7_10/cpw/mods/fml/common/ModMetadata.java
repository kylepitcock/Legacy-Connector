package legacyconnector.v1_7_10.cpw.mods.fml.common;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import legacyconnector.v1_7_10.cpw.mods.fml.common.versioning.ArtifactVersion;

public class ModMetadata {
    public String modId;
    public String name;
    public String description = "";
    public String url = "";
    public String updateUrl = "";
    public String logoFile = "";
    public String version = "";
    public List<String> authorList = new ArrayList<>();
    public String credits = "";
    public String parent = "";
    public String[] screenshots = new String[0];
    /** The container of the mod named by {@link #parent} (set once the mod list is known). */
    public ModContainer parentMod;
    /** The containers of the mods naming this one as their parent. */
    public List<ModContainer> childMods = new ArrayList<>();
    public boolean useDependencyInformation;
    public Set<ArtifactVersion> requiredMods = new HashSet<>();
    public List<ArtifactVersion> dependencies = new ArrayList<>();
    public List<ArtifactVersion> dependants = new ArrayList<>();
    public boolean autogenerated = true;

    public ModMetadata() {
    }

    public String getChildModCountString() {
        return String.format("%d child mod%s", childMods.size(), childMods.size() != 1 ? "s" : "");
    }

    public String getAuthorList() {
        return String.join(", ", authorList);
    }

    public String getChildModList() {
        List<String> names = new ArrayList<>();
        for (ModContainer c : childMods) names.add(c.getName());
        return String.join(", ", names);
    }

    public String printableSortingRules() {
        return "";
    }

    /** Links parent and child mods by their metadata's {@code parent} names, as FML did when it sorted the mod list. */
    static void mcc$linkFamilies(java.util.Map<String, ModContainer> mods) {
        for (ModContainer c : mods.values()) {
            ModMetadata md;
            try {
                md = c.getMetadata();
            } catch (RuntimeException | LinkageError e) {
                continue;
            }
            if (md == null || md.parent == null || md.parent.isEmpty() || md.parentMod != null) continue;
            ModContainer parent = mods.get(md.parent);
            if (parent == null || parent == c) continue;
            md.parentMod = parent;
            ModMetadata pmd = parent.getMetadata();
            if (pmd != null && !pmd.childMods.contains(c)) pmd.childMods.add(c);
        }
    }
}
