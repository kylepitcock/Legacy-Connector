    public int readVarInt() {
        int value = 0;
        int shift = 0;
        byte b;
        do {
            b = readByte();
            value |= (b & 127) << shift++ * 7;
            if (shift > 5) throw new RuntimeException("VarInt too big");
        } while ((b & 128) == 128);
        return value;
    }

    public long readVarLong() {
        long value = 0L;
        int shift = 0;
        byte b;
        do {
            b = readByte();
            value |= (long) (b & 127) << shift++ * 7;
            if (shift > 10) throw new RuntimeException("VarLong too big");
        } while ((b & 128) == 128);
        return value;
    }

    public PacketBuffer writeUniqueId(UUID uuid) {
        writeLong(uuid.getMostSignificantBits());
        writeLong(uuid.getLeastSignificantBits());
        return this;
    }

    public UUID readUniqueId() {
        return new UUID(readLong(), readLong());
    }

    public PacketBuffer writeVarInt(int value) {
        while ((value & -128) != 0) {
            writeByte(value & 127 | 128);
            value >>>= 7;
        }
        writeByte(value);
        return this;
    }

    public PacketBuffer writeVarLong(long value) {
        while ((value & -128L) != 0L) {
            writeByte((int) (value & 127L) | 128);
            value >>>= 7;
        }
        writeByte((int) value);
        return this;
    }

    /** A compound in the 1.12 form: a single 0 byte for null, else the unnamed tag. */
    public PacketBuffer writeCompoundTag(NBTTagCompound tag) {
        if (tag == null) {
            writeByte(0);
        } else {
            try {
                net.minecraft.nbt.NbtIo.writeAnyTag(tag.mcc$modern(), new ByteBufOutputStream(this));
            } catch (IOException e) {
                throw new io.netty.handler.codec.EncoderException(e);
            }
        }
        return this;
    }

    public NBTTagCompound readCompoundTag() throws IOException {
        int start = readerIndex();
        if (readByte() == 0) return null;
        readerIndex(start);
        try {
            var tag = net.minecraft.nbt.NbtIo.readAnyTag(new ByteBufInputStream(this), net.minecraft.nbt.NbtAccounter.create(2097152L));
            return tag instanceof net.minecraft.nbt.CompoundTag c ? new NBTTagCompound(c) : new NBTTagCompound();
        } catch (RuntimeException e) {
            throw new IOException(e);
        }
    }

    public PacketBuffer writeItemStack(ItemStack stack) {
        if (stack == null || stack.isEmpty()) {
            writeShort(-1);
        } else {
            writeShort(Item.getIdFromItem(stack.getItem()));
            writeByte(stack.getCount());
            writeShort(stack.getMetadata());
            writeCompoundTag(stack.getTagCompound());
        }
        return this;
    }

    public ItemStack readItemStack() throws IOException {
        int id = readShort();
        if (id < 0) return ItemStack.EMPTY;
        int count = readByte();
        int meta = readShort();
        ItemStack stack = new ItemStack(Item.getItemById(id), count, meta);
        stack.setTagCompound(readCompoundTag());
        return stack;
    }

    public String readString(int maxLength) {
        int length = readVarInt();
        if (length > maxLength * 4) throw new io.netty.handler.codec.DecoderException("The received encoded string buffer length is longer than maximum allowed (" + length + " > " + maxLength * 4 + ")");
        if (length < 0) throw new io.netty.handler.codec.DecoderException("The received encoded string buffer length is less than zero! Weird string!");
        String text = toString(readerIndex(), length, StandardCharsets.UTF_8);
        readerIndex(readerIndex() + length);
        if (text.length() > maxLength) throw new io.netty.handler.codec.DecoderException("The received string length is longer than maximum allowed (" + length + " > " + maxLength + ")");
        return text;
    }

    public PacketBuffer writeString(String text) {
        byte[] bytes = text.getBytes(StandardCharsets.UTF_8);
        if (bytes.length > 32767) throw new io.netty.handler.codec.EncoderException("String too big (was " + bytes.length + " bytes encoded, max 32767)");
        writeVarInt(bytes.length);
        writeBytes(bytes);
        return this;
    }

