    public long[] readLongArray(long[] into) {
        return readLongArray(into, readableBytes() / 8);
    }

    public long[] readLongArray(long[] into, int maxLength) {
        int length = readVarInt();
        if (into == null || into.length != length) {
            if (length > maxLength) throw new io.netty.handler.codec.DecoderException("LongArray with size " + length + " is bigger than allowed " + maxLength);
            into = new long[length];
        }
        for (int i = 0; i < into.length; i++) into[i] = readLong();
        return into;
    }

