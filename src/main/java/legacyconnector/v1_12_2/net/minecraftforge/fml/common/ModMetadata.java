package legacyconnector.v1_12_2.net.minecraftforge.fml.common;

import java.util.ArrayList;
import java.util.List;

public class ModMetadata {
    public String modId;
    public String name;
    public String description = "";
    public String url = "";
    public String updateUrl = "";
    public String logoFile = "";
    public String version = "";
    public List<String> authorList = new ArrayList<>();
    public String credits = "";
    public String parent = "";
    public String[] screenshots = new String[0];
    public List<String> requiredMods = new ArrayList<>();
    public List<String> dependencies = new ArrayList<>();
    public List<String> dependants = new ArrayList<>();
    public boolean useDependencyInformation;
    public boolean autogenerated = true;
    /** The mod this one is a sub-mod of (mods register their add-on modules with it). */
    public ModContainer parentMod;
    /** Sub-mods: mods add their own modules here ({@code getMetadata().childMods.add(...)}), so it must never be null. */
    public List<ModContainer> childMods = new ArrayList<>();

    public ModMetadata() {
    }

    public String getChildModCountString() {
        return childMods == null || childMods.isEmpty() ? "" : String.format("(%d child mod%s)", childMods.size(), childMods.size() == 1 ? "" : "s");
    }

    public String getAuthorList() {
        return String.join(", ", authorList);
    }
}
