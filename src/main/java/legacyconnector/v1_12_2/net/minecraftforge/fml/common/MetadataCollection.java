package legacyconnector.v1_12_2.net.minecraftforge.fml.common;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/** A mod's {@code mcmod.info}: descriptions per mod id, as FML read them for the mod list. */
public class MetadataCollection {
    private final Map<String, ModMetadata> byId = new HashMap<>();

    public static MetadataCollection from(InputStream input, String sourceName) {
        MetadataCollection out = new MetadataCollection();
        if (input == null) return out;
        try (InputStreamReader reader = new InputStreamReader(input, StandardCharsets.UTF_8)) {
            JsonElement root = JsonParser.parseReader(reader);
            JsonArray list = root.isJsonArray() ? root.getAsJsonArray()
                    : root.isJsonObject() && root.getAsJsonObject().has("modList") ? root.getAsJsonObject().getAsJsonArray("modList") : new JsonArray();
            for (JsonElement e : list) {
                if (!e.isJsonObject()) continue;
                JsonObject o = e.getAsJsonObject();
                if (!o.has("modid")) continue;
                ModMetadata md = new ModMetadata();
                md.modId = o.get("modid").getAsString();
                md.name = string(o, "name", md.modId);
                md.version = string(o, "version", "");
                md.description = string(o, "description", "");
                md.url = string(o, "url", "");
                md.credits = string(o, "credits", "");
                md.logoFile = string(o, "logoFile", "");
                md.parent = string(o, "parent", "");
                if (o.has("authorList") && o.get("authorList").isJsonArray()) o.getAsJsonArray("authorList").forEach(a -> md.authorList.add(a.getAsString()));
                md.autogenerated = false;
                out.byId.put(md.modId, md);
            }
        } catch (Exception ignored) {
            // unreadable info: mods fall back to generated metadata
        }
        return out;
    }

    private static String string(JsonObject o, String key, String fallback) {
        return o.has(key) && o.get(key).isJsonPrimitive() ? o.get(key).getAsString() : fallback;
    }

    public ModMetadata getMetadataForId(String modId, Map<String, Object> extraData) {
        ModMetadata md = byId.get(modId);
        if (md == null) {
            md = new ModMetadata();
            md.modId = modId;
            md.name = extraData != null && extraData.get("name") != null ? String.valueOf(extraData.get("name")) : modId;
            if (extraData != null && extraData.get("version") != null) md.version = String.valueOf(extraData.get("version"));
        }
        return md;
    }
}
