#!/usr/bin/env python3
"""Generates 1.12.2 constant holders: init/SoundEvents, init/MobEffects and init/Enchantments (static fields typed SoundEvent / Potion /
Enchantment, each a wrapper over the modern vanilla object), from the legacy field list. usage: tools/gen_constants_1122.py"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FIELDS = os.path.join(ROOT, "loader", "src", "main", "resources", "legacyconnector", "legacy", "1.12.2", "fields.txt")
OUT = os.path.join(ROOT, "src", "main", "java", "legacyconnector", "v1_12_2", "net", "minecraft", "init")


def collect(owner, desc):
    out = []
    for line in open(FIELDS, encoding="utf-8"):
        p = line.split()
        if len(p) >= 4 and p[1] == owner and p[3] == desc:
            out.append(p[2])
    return sorted(set(out))


def emit(cls, owner, desc, java_type, factory, doc):
    names = collect(owner, desc)
    lines = ["package legacyconnector.v1_12_2.net.minecraft.init;", "",
             "import org.kylepitcock.legacyconnector.v1_12_2.bridge.Vanilla1122;", "",
             "/** %s (generated by tools/gen_constants_1122.py). */" % doc,
             "public class %s {" % cls]
    for n in names:
        lines.append("    public static final %s %s = Vanilla1122.%s(\"%s\");" % (java_type, n, factory, n))
    lines.append("}")
    with open(os.path.join(OUT, cls + ".java"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(cls, len(names))


emit("SoundEvents", "net/minecraft/init/SoundEvents", "Lnet/minecraft/util/SoundEvent;", "legacyconnector.v1_12_2.net.minecraft.util.SoundEvent",
     "sound", "1.12.2 vanilla sounds: wrappers over the modern sound events")
emit("MobEffects", "net/minecraft/init/MobEffects", "Lnet/minecraft/potion/Potion;", "legacyconnector.v1_12_2.net.minecraft.potion.Potion",
     "effect", "1.12.2 vanilla potion effects")
emit("Enchantments", "net/minecraft/init/Enchantments", "Lnet/minecraft/enchantment/Enchantment;", "legacyconnector.v1_12_2.net.minecraft.enchantment.Enchantment",
     "enchantment", "1.12.2 vanilla enchantments")

emit("Biomes", "net/minecraft/init/Biomes", "Lnet/minecraft/world/biome/Biome;", "legacyconnector.v1_12_2.net.minecraft.world.biome.Biome", "biome",
     "1.12.2 vanilla biomes (names only)")
