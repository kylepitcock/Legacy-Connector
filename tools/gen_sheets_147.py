#!/usr/bin/env python3
"""Writes src/main/resources/legacyconnector/v1_6_4/sheet-terrain.tsv and sheet-items.tsv: for each of the 256 tiles of Minecraft 1.4.7's
/terrain.png and /gui/items.png the 1.7.10 texture name (textures/blocks/<name>.png, textures/items/<name>.png) it shows. Mods that copy the look of
vanilla blocks and items use the vanilla sheet indices (Block(id, 1, Material) is stone's tile); SpriteSheets147 maps them to sprites with these tables.

The tiles are matched by pixels: an exact match first, then the closest texture (mean absolute difference below a threshold, for the textures
redrawn between 1.4.7 and 1.7.10). Animated 1.7.10 textures are strips of frames: the first frame counts. Several names with the same pixels:
the first in this order wins (plain names before *_overlay, *_top/*_side variants after the base name), which is a cosmetic choice.

usage: tools/gen_sheets_147.py <client-1.4.7.jar> <client-1.7.10.jar>
"""
import io, os, sys, zipfile
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "main", "resources", "legacyconnector", "v1_6_4")


def frames(z, folder):
    out = {}
    for n in z.namelist():
        if n.startswith(folder) and n.endswith(".png"):
            im = Image.open(io.BytesIO(z.read(n))).convert("RGBA")
            w = im.size[0]
            if w >= 16:
                out[n[len(folder):-4]] = im.crop((0, 0, w, w)).resize((16, 16), Image.NEAREST) if w != 16 else im.crop((0, 0, 16, 16))
    return out


def tiles(z, sheet):
    im = Image.open(io.BytesIO(z.read(sheet))).convert("RGBA")
    t = im.size[0] // 16
    return [im.crop(((i % 16) * t, (i // 16) * t, (i % 16) * t + t, (i // 16) * t + t)).resize((16, 16), Image.NEAREST) for i in range(256)]


def key(im):
    px = list(im.getdata())
    return tuple((r, g, b, a) if a else (0, 0, 0, 0) for r, g, b, a in px)


def diff(a, b):
    total = 0
    for (r1, g1, b1, a1), (r2, g2, b2, a2) in zip(a, b):
        total += abs(a1 - a2) + (0 if a1 == 0 and a2 == 0 else abs(r1 - r2) + abs(g1 - g2) + abs(b1 - b2))
    return total / 256.0


def order(name):
    return (name.endswith("_overlay"), "_" in name, len(name), name)


# tiles drawn by animations or redrawn too much for the pixel match
MANUAL = {"terrain.png": {12: "flower_rose", 144: "lapis_block", 205: "water_still", 206: "water_flow", 237: "lava_still", 238: "lava_flow", 31: "fire_layer_0", 47: "fire_layer_1"},
          "gui/items.png": {70: "clock"}}


def build(old, new, sheet, folder, threshold):
    cand = frames(new, folder)
    exact = {}
    keyed = {}
    for name in sorted(cand, key=order):
        k = key(cand[name])
        exact.setdefault(k, name)
        keyed[name] = k
    rows = []
    for i, t in enumerate(tiles(old, sheet)):
        k = key(t)
        if all(p[3] == 0 for p in k):
            continue
        name = exact.get(k)
        how = "exact"
        if name is None:
            best = min(keyed, key=lambda n: diff(k, keyed[n]))
            d = diff(k, keyed[best])
            if d <= threshold:
                name, how = best, "close %.1f" % d
        if name is None and i in MANUAL.get(sheet, {}):
            name, how = MANUAL[sheet][i], "manual"
        rows.append((i, name, how))
    return rows


old = zipfile.ZipFile(sys.argv[1])
new = zipfile.ZipFile(sys.argv[2])
for sheet, folder, outname, thr in (("terrain.png", "assets/minecraft/textures/blocks/", "sheet-terrain.tsv", 30), ("gui/items.png", "assets/minecraft/textures/items/", "sheet-items.tsv", 30)):
    rows = build(old, new, sheet, folder, thr)
    ok = [r for r in rows if r[1]]
    with open(os.path.join(OUT, outname), "w", encoding="utf-8", newline="\n") as f:
        f.write("# 1.4.7 /%s tile index -> 1.7.10 texture name; generated by tools/gen_sheets_147.py (pixel match: %d of %d non-empty tiles matched)\n" % (sheet, len(ok), len(rows)))
        for i, name, how in rows:
            if name:
                f.write("%d\t%s\t# %s\n" % (i, name, how))
    print(sheet, "matched", len(ok), "of", len(rows), "unmatched:", [r[0] for r in rows if not r[1]])
