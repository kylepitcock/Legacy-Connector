#!/usr/bin/env python3
"""Writes loader/src/main/resources/legacyconnector/forward/1.4.7/flat-names.tsv: the flat MCP 6.x class names of Minecraft 1.4.7
(`net/minecraft/src/Block`, which is how every 1.4.7 mod references the game) to the packaged names of 1.5.2 and later
(`net/minecraft/block/Block`). From the packages.csv of Forge 6.6.2.534 (fml/conf), with the two classes 1.5.2 moved again taken from its packages.csv.
Classes without an entry (the ModLoader emulation that FML keeps in net.minecraft.src: BaseMod, ModLoader, MLProp, ...) stay flat.

usage: tools/gen_forward_147.py   (needs tools/fetch_devtools.sh data: build/devtools/mcp/forge147-src.zip and forge152-src.zip)
The 1.4.7 -> 1.5.2 -> 1.6.4 -> 1.7.10 class renames are chained at run time (LegacyVersion.forwardTableIds, ForwardRenames.map).
"""
import csv, io, os, zipfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DEV = os.path.join(ROOT, "build", "devtools", "mcp")


def packages(zname):
    with zipfile.ZipFile(os.path.join(DEV, zname)) as z:
        return {r[0]: r[1] for r in csv.reader(io.TextIOWrapper(z.open("forge/fml/conf/packages.csv"), "utf-8")) if r and r[0] != "class"}


p147, p152 = packages("forge147-src.zip"), packages("forge152-src.zip")
classes = set()
for line in open(os.path.join(ROOT, "loader", "src", "main", "resources", "legacyconnector", "legacy", "1.4.7", "hierarchy.txt"), encoding="utf-8"):
    name = line.split()[0]
    if name.startswith("net/minecraft/src/"):
        classes.add(name[len("net/minecraft/src/"):].split("$")[0])
rows = []
for c in sorted(classes | set(p147)):
    pkg = p152.get(c) or p147.get(c)
    if pkg:
        rows.append("net/minecraft/src/%s\t%s/%s" % (c, pkg, c))
out = os.path.join(ROOT, "loader", "src", "main", "resources", "legacyconnector", "forward", "1.4.7")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "flat-names.tsv"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# Forge 1.4.7 flat class names (MCP 6.x) -> packaged names of 1.5.2 (old<TAB>new); outer classes only, a nested class follows its outer one. Generated by tools/gen_forward_147.py\n")
    f.write("\n".join(rows) + "\n")
print("wrote", len(rows), "flat names;", len(classes - set(p147)), "classes stay flat:", sorted(classes - set(p147)))
