#!/usr/bin/env python3
"""Writes src/main/resources/legacyconnector/legacy/leaf-fingerprints.txt, the table LeafModernizer uses to recognise legacy
mod leaf textures that are recolours of the old (1.7.10 / 1.12.2) vanilla leaves. It holds hashes only, never pixels:

  L <modern> <hash>   a leaf texture whose cut-out mask (16x16, row by row, one byte per pixel: 1 when alpha >= 128, else 0)
                      hashes to <hash> (first 16 hex digits of SHA-1) has the shape of an old vanilla leaf texture; the modern
                      vanilla texture textures/<modern>.png gives the new pattern

The old oak, birch, acacia and dark oak leaves share one mask (and one pattern): they map to the modern oak leaves.

usage: tools/gen_leaf_fingerprints.py <1.7.10 client jar>"""
import hashlib, io, os, sys, zipfile
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "main", "resources", "legacyconnector", "legacy", "leaf-fingerprints.txt")
OLD = [("oak", "block/oak_leaves"), ("birch", "block/oak_leaves"), ("acacia", "block/oak_leaves"), ("big_oak", "block/oak_leaves"),
       ("spruce", "block/spruce_leaves"), ("jungle", "block/jungle_leaves")]


def mask_hash(img):
    img = img.convert("RGBA")
    alpha = img.tobytes()[3::4]
    return hashlib.sha1(bytes(1 if a >= 128 else 0 for a in alpha)).hexdigest()[:16]


def main():
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    lines = {}
    with zipfile.ZipFile(sys.argv[1]) as z:
        for legacy, modern in OLD:
            img = Image.open(io.BytesIO(z.read(f"assets/minecraft/textures/blocks/leaves_{legacy}.png")))
            h = mask_hash(img)
            if h in lines and lines[h] != modern:
                print(f"leaves_{legacy}: mask shared with another kind, kept {lines[h]}", file=sys.stderr)
                continue
            lines[h] = modern
    with open(OUT, "w", newline="\n") as f:
        f.write("# Generated by tools/gen_leaf_fingerprints.py: cut-out mask hashes of the old vanilla leaves, no pixels.\n")
        for h, modern in sorted(lines.items(), key=lambda e: e[1]):
            f.write(f"L {modern} {h}\n")
    print(f"{len(lines)} leaf masks -> {OUT}")


if __name__ == "__main__":
    main()
