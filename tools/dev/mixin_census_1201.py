#!/usr/bin/env python3
"""Mixin target census of Forge 1.20.1 jars (offline, no game).

usage: mixin_census_1201.py <jar-dir-or-jar>... [--report out.md] [--top N] [--from-report build/reports/mixinSurvey1201.txt]

Runs `./gradlew mixinSurvey1201` (loader transform/Mixin1201Survey: the layer's own target proof against the 1.21.1 class index, after the class and member
renames of the tables) and ranks every injection target the proof drops, counted by number of mods (jars), in three lists: method selectors, @At targets and
whole mixin classes dropped (missing target class / @Shadow member). Targets that TargetRemap (forward/1.20.1/mixin-targets.tsv) already remaps do not show:
the proof turns them into repairs.
"""
import argparse, collections, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def run_survey(inputs):
    report = ROOT / "build" / "reports" / "mixinSurvey1201.txt"
    report.parent.mkdir(parents=True, exist_ok=True)
    jars = ",".join(str(pathlib.Path(i).resolve()) for i in inputs)
    gradle = "gradlew.bat" if sys.platform == "win32" else "./gradlew"
    subprocess.run([str(ROOT / gradle), "mixinSurvey1201", "-q", f"-PsurveyJars={jars}", f"-PsurveyReport={report}"], cwd=ROOT, check=True)
    return report




def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("inputs", nargs="*")
    ap.add_argument("--from-report")
    ap.add_argument("--report", default=str(ROOT / "tools" / "dev" / "agent-tasks" / "1.20.1-mixin-targets.md"))
    ap.add_argument("--top", type=int, default=60)
    a = ap.parse_args()
    rep = pathlib.Path(a.from_report) if a.from_report else run_survey(a.inputs)
    text = rep.read_text(encoding="utf-8", errors="replace")
    head = text.split("\n\n", 1)[0]
    by = {"method": collections.defaultdict(set), "at": collections.defaultdict(set), "class": collections.defaultdict(set)}
    reasons = {}
    for line in text.splitlines():
        if line.startswith("@DROP\t"):
            _, jar, kind, target, reason = (line.split("\t") + [""])[:5]
            by[kind][target].add(jar)
            reasons.setdefault((kind, target), reason)
        elif line.startswith("@CLASS\t"):
            _, jar, what = line.split("\t", 2)
            by["class"][what].add(jar)
    out = ["# 1.20.1 mixin targets that do not resolve against 1.21.1", "",
           "Generated by `tools/dev/mixin_census_1201.py` (offline: `Mixin1201Survey`, the layer's own target proof). Counts are mods (jars) with at least one such injection.", "",
           "```", head.strip(), "```", ""]
    titles = {"method": "Injection method selectors dropped (target gone, or its signature changed beyond added parameters)",
              "at": "@At targets dropped (call/field gone or reshaped)", "class": "Mixin classes dropped as a whole (target class or @Shadow/@Accessor member missing)"}
    for kind in ("method", "at", "class"):
        rows = sorted(by[kind].items(), key=lambda kv: (-len(kv[1]), kv[0]))
        out += [f"## {titles[kind]}", "", f"{len(rows)} distinct targets.", "", "| mods | target | why |", "|---|---|---|"]
        for t, jars in rows[: a.top]:
            r = reasons.get((kind, t), "")
            out.append(f"| {len(jars)} | `{t}` | {r.replace('|', '/')[:150]} |")
        out.append("")
    pathlib.Path(a.report).write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out[:12]))
    print(f"written {a.report}")


if __name__ == "__main__":
    main()
