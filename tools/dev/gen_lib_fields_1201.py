#!/usr/bin/env python3
"""Generates lib-fields.tsv rows for registry fields of a library that changed their type (RegistryObject in 1.20.1; a Supplier, Holder or DeferredItem now).

usage: gen_lib_fields_1201.py <diff.tsv from ./gradlew libApiDiff> <forward/1.20.1 dir> <library label>

The report's "retype" lines have the old field descriptor and the new one. The translator already turned RegistryObject into DeferredHolder, so a row
reads the new field and converts it back: nothing when the new type is a DeferredHolder subtype (DeferredItem, DeferredBlock), RegistryCompat.fromSupplier
for a Supplier, RegistryCompat.fromHolder for a Holder. The block between the markers of <library label> is replaced; the rest of the file is kept.
"""
import re, sys, pathlib

OLD = "Lnet/minecraftforge/registries/RegistryObject;"
DEFERRED = "Lnet/neoforged/neoforge/registries/DeferredHolder;"
SUBTYPES = ("Lnet/neoforged/neoforge/registries/DeferredItem;", "Lnet/neoforged/neoforge/registries/DeferredBlock;")


def main():
    diff, d, label = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
    rows = []
    for line in diff.read_text(encoding="utf8").splitlines():
        p = line.split("\t")
        if p[0] != "retype":
            continue
        m = re.match(r"(.+)\.([^.:]+):(.+)$", p[1])
        owner, name, old = m.groups()
        new = p[2]
        if old != OLD:
            continue
        if new in SUBTYPES:
            post = "-"
        elif new == "Ljava/util/function/Supplier;":
            post = "RegistryCompat.fromSupplier"
        elif new == "Lnet/minecraft/core/Holder;":
            post = "RegistryCompat.fromHolder"
        else:
            continue
        rows.append(f"{owner}\t{name}\t{DEFERRED}\t-\t{new}\t{post}")
    begin = f"# BEGIN generated by tools/dev/gen_lib_fields_1201.py ({label})"
    end = f"# END generated ({label})"
    path = d / "lib-fields.tsv"
    text = path.read_text(encoding="utf8")
    text = re.sub(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", "", text, flags=re.S)
    text = text.rstrip("\n") + "\n" + begin + "\n" + "\n".join(rows) + "\n" + end + "\n"
    path.write_text(text, encoding="utf8", newline="\n")
    print(len(rows), "field rows for", label)


main()
