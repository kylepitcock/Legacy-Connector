#!/usr/bin/env python3
"""Generates the GeckoLib 4.8 -> 4.9 colour rows of lib-calls.tsv and lib-bridges.tsv from a libApiDiff report.

usage: gen_geckolib_1201.py <diff.tsv from ./gradlew libApiDiff ... -Prenames=lib-classes.tsv> <forward/1.20.1 dir>

The report's "colour" lines are methods whose trailing four colour floats became one packed ARGB int. For each one:
- lib-calls.tsv: a call of the old method keeps its target, packs the floats with GeckoCompat.pack ("=colour");
- lib-bridges.tsv: a mod class that overrides the old method gets the new method, which calls the old one with the floats unpacked.
Interface methods (GeoRenderer) are also listed for each renderer class, because a call is written against the receiver's class.
The block between the markers is replaced; everything else in the files is kept.
"""
import re, sys, pathlib

BEGIN = "# BEGIN generated by tools/dev/gen_geckolib_1201.py (GeckoLib colour)"
END = "# END generated (GeckoLib colour)"
RENDERERS = ["GeoRenderer", "GeoEntityRenderer", "GeoBlockRenderer", "GeoItemRenderer", "GeoArmorRenderer", "GeoReplacedEntityRenderer",
             "GeoObjectRenderer", "DynamicGeoEntityRenderer", "DyeableGeoArmorRenderer", "DynamicGeoItemRenderer"]
PKG = "software/bernie/geckolib/renderer/"


def params(desc):
    inner = desc[1:desc.index(")")]
    out, i = [], 0
    while i < len(inner):
        j = i
        while inner[j] == "[":
            j += 1
        j = inner.index(";", j) + 1 if inner[j] == "L" else j + 1
        out.append(inner[i:j])
        i = j
    return out


def rename(desc, ren):
    """Class names of a descriptor as the translator has them when the tables are applied (after the lib-classes.tsv renames)."""
    return re.sub(r"L([^;]+);", lambda m: "L" + ren.get(m.group(1), m.group(1)) + ";", desc)


def main():
    diff, d = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    ren = {}
    for l in (d / "lib-classes.tsv").read_text(encoding="utf8").splitlines():
        a = l.split("	")
        if len(a) == 2 and not l.startswith("#"):
            ren[a[0]] = a[1]
    calls, bridges = [], []
    rows = []
    for line in diff.read_text(encoding="utf8").splitlines():
        p = line.split("\t")
        if p[0] != "colour":
            continue
        m = re.match(r"(.+)\.([^.(]+)(\(.*)$", p[1])
        rows.append((m.group(1), m.group(2), rename(m.group(3), ren), p[2]))
    owners_of_interface = [PKG + r for r in RENDERERS]
    seen = set()
    for owner, name, old, new in rows:
        targets = [owner]
        if owner == PKG + "GeoRenderer":
            targets = owners_of_interface
        for o in targets:
            key = (o, name, old)
            if key in seen:
                continue
            seen.add(key)
            calls.append(f"{o}\t{name}\t{old}\t=colour\t-\t{new}")
        n = len(params(new)) - 1
        toks = [str(i) for i in range(n)] + [f"GeckoCompat.{c}@{n}" for c in ("red", "green", "blue", "alpha")]
        bridges.append(f"{owner}\t{name}\t{old}\t{name}\t{new}\t{','.join(toks)}\t-\t-")
    for f, extra in (("lib-calls.tsv", calls), ("lib-bridges.tsv", bridges)):
        path = d / f
        text = path.read_text(encoding="utf8")
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S)
        text = text.rstrip("\n") + "\n" + BEGIN + "\n" + "\n".join(extra) + "\n" + END + "\n"
        path.write_text(text, encoding="utf8", newline="\n")
    print(len(calls), "call rows,", len(bridges), "bridge rows")


main()
