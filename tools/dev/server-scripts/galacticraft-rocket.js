// Rocket: spawn a tier 1 rocket at the pad in the overworld, fuel it, put the player aboard and ignite. Read with galacticraft-rocket-read.js.
var lv = GC.level(0);
var X = 302, Y = 200, Z = 302;
GC.load(lv, X, Z, 2);
GC.fill(lv, X - 4, Y - 1, Z - 4, X + 4, Y - 1, Z + 4, Blocks.STONE);
GC.fill(lv, X - 4, Y, Z - 4, X + 4, Y + 10, Z + 4, Blocks.AIR);
var ET = BR.ENTITY_TYPE;
var names = [];
ET.keySet().forEach(function (k) { if (("" + k).indexOf("rocket") >= 0) names.push("" + k); });
var o = "rocket types " + names.join(",") + "\n";
var type = ET.get(RL.parse("galacticraftcore:rocket_t1"));
var e = type.create(lv);
e.moveTo(X + 0.5, Y + 0.4, Z + 0.5, 0, 0);
lv.addFreshEntity(e);
var rocket = Java.type("org.kylepitcock.legacyconnector.v1_12_2.bridge.EntityBridge1122").wrap(e);
o += "legacy " + rocket.getClass().getName() + " tank " + rocket.fuelTank + "\n";
var GCF = Java.type("micdoodle8.mods.galacticraft.core.GCFluids");
var FS = Java.type("legacyconnector.v1_12_2.net.minecraftforge.fluids.FluidStack");
var filled = rocket.fuelTank.fill(new FS(GCF.fluidFuel, 2000), true);
o += "filled " + filled + "\n";
var p = GC.player();
p.teleportTo(lv, X + 0.5, Y + 0.2, Z + 0.5, 0, 0);
var ok = p.startRiding(e, true);
o += "riding " + ok + " player dim " + p.level().dimension().location() + "\n";
ROCKET = e;
LROCKET = rocket;
rocket.rocketType = Java.type("micdoodle8.mods.galacticraft.api.entity.IRocketType$EnumRocketType").DEFAULT;
rocket.ignite();
o += "launchPhase " + rocket.launchPhase + "\n";
o;
